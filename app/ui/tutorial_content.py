"""「使用教程」窗口里显示的内容（纯数据）。

把文案和配图放在这里，:mod:`app.ui.tutorial` 只负责渲染。
``image`` 块里写的是 ``assets/tutorial/``（英文是 ``en/``）下的文件名，
由 ``tools/make-tutorial-images.py`` 用真实界面截图 + 红圈/编号标注生成。

块的类型：

==== ====================================================
类型  说明
==== ====================================================
h1   章节大标题
h2   小节标题
p    一段正文（自动换行）
bullets  项目符号列表
steps    带编号的步骤列表
note 提示条（浅蓝底）
code 等宽代码块
table   表格（表头 + 行）
image   配图 + 图注
==== ====================================================
"""

from __future__ import annotations

from typing import Any


def h1(text: str) -> tuple:
    return ("h1", text)


def h2(text: str) -> tuple:
    return ("h2", text)


def p(text: str) -> tuple:
    return ("p", text)


def bullets(*items: str) -> tuple:
    return ("bullets", list(items))


def steps(*items: str) -> tuple:
    return ("steps", list(items))


def note(text: str) -> tuple:
    return ("note", text)


def code(text: str) -> tuple:
    return ("code", text)


def table(headers: list[str], rows: list[list[str]]) -> tuple:
    return ("table", headers, rows)


def image(name: str, caption: str) -> tuple:
    return ("image", name, caption)


